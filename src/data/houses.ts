/** Номер моделі Nordy з назви/slug (NORDY 130 → 130 м²). */
export function getNordyModelSqm(house: HouseType): number {
  const fromName = house.name.match(/NORDY\s*(\d+(?:\.\d+)?)/i);
  if (fromName) return Number(fromName[1]);
  const fromSlug = house.slug.match(/nordy-(\d+(?:\.\d+)?)/i);
  if (fromSlug) return Number(fromSlug[1]);
  return house.dimensions?.totalArea?.meters ?? house.squareMeters;
}

/** Загальна площа будинку (м²) — Nordy: номер моделі; інші — з даних. */
export function getHouseTotalAreaSqm(house: HouseType): number {
  if (house.category === 'NORDY') return getNordyModelSqm(house);
  return house.dimensions?.totalArea?.meters ?? house.squareMeters;
}

// Helper function to get houses by category
export const getHousesByCategory = (category: string) => {
  if (category === 'ALL') return houseData;
  return houseData.filter(house => house.category === category);
};

// Helper function to get house by slug
export const getHouseBySlug = (slug: string) => {
  return houseData.find(house => house.slug === slug);
};

// Get unique categories
export const getCategories = () => {
  const categories = ['ALL', ...new Set(houseData.map(house => house.category))];
  return categories;
};
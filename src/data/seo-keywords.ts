/**
 * Спільні SEO-ключові слова та географія для мета-тегів на сторінках.
 * Поєднуйте з ключовими словами конкретної сторінки.
 */

export const SEO_LOCATIONS =
  'Україна, Київ, Львів, Одеса, Харків, Дніпро, Вінниця, Закарпаття, Карпати, західна Україна, доставка по Україні';

export const SEO_BASE_TERMS =
  'модульні будинки, каркасні будинки, зведення будинків під ключ, SIP-будинки, енергоефективні будинки, екологічне будівництво, швидке будівництво, префаб-будинки, сучасні котеджі, будинки заводського виготовлення';

export const SEO_SERVICES =
  'проєктування модульних будинків, монтаж каркасного будинку, доставка модулів, комплектація під ключ, консультація з будівництва';

/** Повний рядок ключових слів: сторінка + локації + базові терміни (опційно послуги). */
export function buildKeywords(
  pageTerms: string,
  options?: { includeServices?: boolean }
): string {
  const parts = [pageTerms, SEO_LOCATIONS, SEO_BASE_TERMS];
  if (options?.includeServices) parts.push(SEO_SERVICES);
  return parts.join(', ');
}
